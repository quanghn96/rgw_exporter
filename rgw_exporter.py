class S3V2Auth(requests.auth.AuthBase):
    """
    Minimal AWS Signature Version 2 signer. Admin Ops requests are plain
    GETs without sub-resources, so only the request path is signed.
    """

    def __init__(self, access_key, secret_key):
        self.access_key = access_key
        self.secret_key = secret_key.encode("utf-8")

    def __call__(self, r):
        date = email.utils.formatdate(usegmt=True)
        r.headers["Date"] = date
        path = urllib.parse.urlsplit(r.url).path
        string_to_sign = "\n".join(
            [
                r.method,
                r.headers.get("Content-MD5", ""),
                r.headers.get("Content-Type", ""),
                date,
                path,
            ]
        )
        digest = hmac.new(
            self.secret_key, string_to_sign.encode("utf-8"), hashlib.sha1
        ).digest()
        signature = base64.b64encode(digest).decode("utf-8")
        r.headers["Authorization"] = "AWS {0}:{1}".format(self.access_key, signature)
        return r


def _num(value, default=0):
    """Coerce JSON values (bool / int / str) to a number for Prometheus."""
    if value is None:
        return default
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _tag_label(tag):
    """Turn a bucket tag key into a valid Prometheus label name."""
    return "tag_" + re.sub(r"[^a-zA-Z0-9_]", "_", tag)


class RADOSGWCollector(object):
    """RADOSGWCollector gathers usage, bucket, user and account data from
    the specified RADOSGW and presents it in a format suitable for pulling via
    a Prometheus server.

    NOTE: By default RADOSGW Servers do not gather usage data and it must be
    enabled by 'rgw enable usage log = true' in the appropriate section
    of ceph.conf see Ceph documentation for details"""

    def __init__(
        self,
        host,
        admin_entry,
        access_key,
        secret_key,
        store,
        insecure,
        timeout,
        tag_list,
        signature="v4",
        region="us-east-1",
        threads=10,
        collectors=ALL_COLLECTORS,
        interval=60,
        retries=3,
    ):
        super(RADOSGWCollector, self).__init__()
        self.host = host
        self.access_key = access_key
        self.secret_key = secret_key
        self.store = store
        self.insecure = insecure
        self.timeout = float(timeout)
        self.tags = [t.strip() for t in tag_list.split(",") if t.strip()]
        self.threads = max(1, int(threads))
        self.collectors = set(collectors)
        self.interval = float(interval)
        self.retries = max(0, int(retries))

        # helpers for default schema
        if not self.host.startswith("http"):
            self.host = "http://{0}".format(self.host)
        # and for request_uri
        if not self.host.endswith("/"):
            self.host = "{0}/".format(self.host)

        self.url = "{0}{1}/".format(self.host, admin_entry.strip("/"))

        if signature == "v2":
            self.auth = S3V2Auth(access_key, secret_key)
        else:
            from requests_aws4auth import AWS4Auth

            self.auth = AWS4Auth(access_key, secret_key, region, "s3")

        self._lock = threading.Lock()
        # Serializes scrapes: metric state lives on the instance.
        self._scrape_lock = threading.Lock()
        # Last metrics gathered by the background thread.
        self._cache = []
        # Prepare Requests Session
        self._session()

    def describe(self):
        """
        Returning an empty list prevents prometheus_client from calling
        collect() (and hitting RGW) when the collector is registered.
        """
        return []

    def collect(self):
        """
        With a positive interval, serve the metrics gathered by the
        background thread so that /metrics answers instantly no matter how
        many users/buckets the cluster has. Otherwise query RGW on each
        scrape.
        """
        if self.interval > 0:
            return list(self._cache)
        return self._scrape()

    def start_background(self):
        """
        Refresh the metric cache every 'interval' seconds in a daemon thread.
        """
        if self.interval <= 0:
            return

        def loop():
            while True:
                start = time.time()
                try:
                    self._cache = self._scrape()
                except Exception:
                    logging.exception("Scrape failed, keeping previous metrics")
                time.sleep(max(0, self.interval - (time.time() - start)))

        threading.Thread(target=loop, name="rgw-scraper", daemon=True).start()

    def _scrape(self):
        with self._scrape_lock:
            return list(self._scrape_unlocked())

    def _scrape_unlocked(self):
        """
        * Collect 'usage' data:
            https://docs.ceph.com/en/latest/radosgw/adminops/#get-usage
        * Collect 'bucket' data:
            https://docs.ceph.com/en/latest/radosgw/adminops/#get-bucket-info
        * Collect 'user' data:
            https://docs.ceph.com/en/latest/radosgw/adminops/#get-user-info
        * Collect 'account' data (Squid+):
            https://docs.ceph.com/en/latest/radosgw/adminops/#get-account-info
        """

        start = time.time()
        self._errors = 0
        self._setup_empty_prometheus_metrics()

        users = {}
        buckets = []
        accounts = {}

        # Users go first: their account_id is needed to map buckets and
        # usage entries to accounts.
        if self.collectors & {"users", "accounts"}:
            users = self._get_rgw_users()

        # Bucket stats are also required to aggregate account usage.
        if self.collectors & {"buckets", "accounts"}:
            rgw_bucket = self._request_data("bucket", {"stats": "True"})
            if isinstance(rgw_bucket, list):
                buckets = [b for b in rgw_bucket if isinstance(b, dict)]
            up = rgw_bucket is not None
        else:
            up = True

        if "accounts" in self.collectors:
            accounts = self._get_rgw_accounts(users, buckets)

        if "usage" in self.collectors:
            rgw_usage = self._request_data(
                "usage", {"show-entries": "True", "show-summary": "False"}
            )
            if rgw_usage:
                self._update_usage_metrics(
                    self._aggregate_usage(rgw_usage), users, accounts
                )

        if "buckets" in self.collectors:
            for bucket in buckets:
                self._update_bucket_metrics(bucket, users, accounts)

        if "users" in self.collectors:
            for uid, info in users.items():
                self._update_user_metrics(uid, info)

        if "accounts" in self.collectors:
            self._update_account_metrics(accounts, users, buckets)

        duration = time.time() - start
        logging.info(
            "Collected %d users, %d buckets, %d accounts in %.1fs (%d errors)",
            len(users),
            len(buckets),
            len(accounts),
            duration,
            self._errors,
        )

        self._prometheus_metrics["up"].add_metric([self.store], 1 if up else 0)
        self._prometheus_metrics["scrape_errors"].add_metric([self.store], self._errors)
        self._prometheus_metrics["scrape_duration_seconds"].add_metric([], duration)
        self._prometheus_metrics["scrape_timestamp"].add_metric([], time.time())
        self._prometheus_metrics["users_collected"].add_metric(
            [self.store], len(users)
        )

        for metric in list(self._prometheus_metrics.values()):
            yield metric

    def _session(self):
        """
        Setup Requests connection settings.
        """
        self.session = requests.Session()
        # With thousands of per-user requests, transient errors (RGW busy,
        # proxy hiccups) are expected: retry them with backoff.
        retry = Retry(
            total=self.retries,
            backoff_factor=0.5,
            status_forcelist=(429, 500, 502, 503, 504),
            allowed_methods=("GET",),
            raise_on_status=False,
        )
        self.session_adapter = requests.adapters.HTTPAdapter(
            pool_connections=self.threads, pool_maxsize=self.threads, max_retries=retry
        )
        self.session.mount("http://", self.session_adapter)
        self.session.mount("https://", self.session_adapter)
        self.session.verify = not self.insecure

        if self.insecure:
            warnings.filterwarnings("ignore", message="Unverified HTTPS request")
            logging.debug("Perform insecure requests")

    def _request_data(self, query, params=None):
        """
        Requests data from RGW. If admin entry and caps is fine - return
        JSON data, otherwise return NoneType.
        """
        url = "{0}{1}".format(self.url, query)
        params = dict(params or {})
        params["format"] = "json"

        try:
            response = self.session.get(
                url, params=params, timeout=self.timeout, auth=self.auth
            )

            if response.status_code == requests.codes.ok:
                logging.debug("GET %s -> %s", response.url, response.status_code)
                return response.json()

            # Usage caps absent, wrong admin entry or unsupported API
            logging.error(
                "Request error [%s] %s: %s",
                response.status_code,
                response.url,
                response.content.decode("utf-8", "replace"),
            )

        # DNS, connection errors, invalid JSON, etc
        except (requests.exceptions.RequestException, ValueError) as e:
            logging.error("Request error %s: %s", url, e)

        with self._lock:
            self._errors += 1
        return None

