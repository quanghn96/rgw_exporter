    # ------------------------------------------------------------------
    # Ownership helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _account_of(owner, users, accounts):
        """
        Resolve the account an owner belongs to. Buckets created by account
        users are owned by the account itself; buckets of regular users are
        owned by the user, who may be a member of an account.
        """
        if owner in accounts or ACCOUNT_ID_RE.match(owner or ""):
            return owner
        info = users.get(owner) or {}
        return info.get("account_id") or ""

    # ------------------------------------------------------------------
    # Usage log
    # ------------------------------------------------------------------

    @staticmethod
    def _aggregate_usage(rgw_usage):
        """
        Builds a dictionary of usage counters keyed by (owner, bucket,
        category) in order to handle owners whose usage data is split into
        multiple entries / bins.
        """
        usage = defaultdict(Counter)

        for entry in rgw_usage.get("entries", []):
            bucket_owner = entry.get("owner") or entry.get("user") or ""

            for bucket in entry.get("buckets", []):
                logging.debug(json.dumps(bucket, indent=4, sort_keys=True))
                bucket_name = bucket.get("bucket") or "bucket_root"

                for category in bucket.get("categories", []):
                    usage[(bucket_owner, bucket_name, category["category"])].update(
                        {
                            "ops": category.get("ops", 0),
                            "successful_ops": category.get("successful_ops", 0),
                            "bytes_sent": category.get("bytes_sent", 0),
                            "bytes_received": category.get("bytes_received", 0),
                        }
                    )
        return usage

    def _update_usage_metrics(self, usage, users, accounts):
        """
        Update prometheus metrics with bucket usage data
        """
        for (owner, bucket, category), data in usage.items():
            labels = [
                bucket,
                owner,
                self._account_of(owner, users, accounts),
                category,
                self.store,
            ]
            for key in ("ops", "successful_ops", "bytes_sent", "bytes_received"):
                self._prometheus_metrics[key].add_metric(labels, data[key])

    # ------------------------------------------------------------------
    # Buckets
    # ------------------------------------------------------------------

    @staticmethod
    def _bucket_main_usage(bucket):
        """
        Return (bytes, utilized_bytes, objects) from 'rgw.main' usage.
        """
        main = (bucket.get("usage") or {}).get("rgw.main") or {}
        # Prefer bytes, instead kbytes
        if "size_actual" in main:
            size = main["size_actual"]
        else:
            size = main.get("size_kb_actual", 0) * 1024
        return size, main.get("size_utilized", 0), main.get("num_objects", 0)

    def _bucket_tag_values(self, bucket):
        """
        Return one value per configured tag (empty string when absent) so
        label values always line up with label names.
        """
        tagset = bucket.get("tagset") or {}
        # Some releases return a list of {"key": .., "val"/"value": ..}
        if isinstance(tagset, list):
            tagset = {
                t.get("key"): t.get("val", t.get("value", ""))
                for t in tagset
                if isinstance(t, dict)
            }
        return [str(tagset.get(t, "")) for t in self.tags]

    def _update_bucket_metrics(self, bucket, users, accounts):
        """
        Method get actual bucket usage (in bytes).
        """
        logging.debug(json.dumps(bucket, indent=4, sort_keys=True))

        owner = bucket.get("owner", "")
        size, utilized, objects = self._bucket_main_usage(bucket)

        labels = [
            bucket.get("bucket", ""),
            owner,
            self._account_of(owner, users, accounts),
            bucket.get("tenant", ""),
            bucket.get("zonegroup", "0"),
            self.store,
        ] + self._bucket_tag_values(bucket)

        m = self._prometheus_metrics
        m["bucket_usage_bytes"].add_metric(labels, size)
        m["bucket_utilized_bytes"].add_metric(labels, utilized)
        m["bucket_usage_objects"].add_metric(labels, objects)
        m["bucket_shards"].add_metric(labels, _num(bucket.get("num_shards")))

        quota = bucket.get("bucket_quota")
        if quota:
            self._add_quota(labels, quota, "bucket_quota")

    def _add_quota(self, labels, quota, prefix):
        m = self._prometheus_metrics
        m[prefix + "_enabled"].add_metric(labels, _num(quota.get("enabled")))
        m[prefix + "_max_size"].add_metric(labels, _num(quota.get("max_size"), -1))
        m[prefix + "_max_size_bytes"].add_metric(
            labels, _num(quota.get("max_size_kb")) * 1024
        )
        m[prefix + "_max_objects"].add_metric(
            labels, _num(quota.get("max_objects"), -1)
        )

